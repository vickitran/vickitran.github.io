	function fmtY(v) {
		if (v >= 10000) return (v / 1000).toFixed(0) + 'k';
		if (v >= 1000) return (v / 1000).toFixed(1) + 'k';
		if (v >= 100) return Math.round(v).toString();
		if (v >= 10) return Math.round(v).toString();
		if (v >= 1) return v.toFixed(1);
		return v.toFixed(2);
	}

	let container;
	onMount(() => {
		draw();
	});

	function draw() {
		if (!container) return;
		d3.select(container).selectAll('*').remove();

		const COLS = SPECIES.length;
		const ROWS = LAKES.length;

		// ── Layout — identical pattern to SmallMultipleLines ──────────────────
		const TITLE_H = 60;
		const DB_H = 50;
		const GRID_TOP = TITLE_H + DB_H;
		const FOOTER_H = spacing.marginDefault.bottom;

		const COL_HDR_H = 32;
		const ROW_LBL_W = 64;
		const GAP_Y = 10;
		const PAD = { l: 36, r: 6, t: 4, b: 22 };

		const ML = spacing.marginDefault.left;
		const MR = spacing.marginDefault.right;
		const usableW = width - ML - MR - ROW_LBL_W;
		const CW = Math.floor(usableW / COLS);
		const CH = Math.round(CW * 0.62);

		const svgH = GRID_TOP + COL_HDR_H + ROWS * (CH + GAP_Y) + FOOTER_H + 18;

		// ── Scales ─────────────────────────────────────────────────────────────
		const xSc = d3
			.scaleLinear()
			.domain([1960, 2020])
			.range([PAD.l, CW - PAD.r]);
		const allVals = LAKES.flatMap((l) => SPECIES.flatMap((s) => RAW[l][s].map((d) => d.y)));
		const globalMax = d3.max(allVals);
		const yGlobal = d3
			.scaleLinear()
			.domain([0, globalMax])
			.range([CH - PAD.b, PAD.t]);
		const lineFn = (ySc) =>
			d3
				.line()
				.x((d) => xSc(d.x))
				.y((d) => ySc(d.y))
				.curve(d3.curveCatmullRom);

		// ── SVG root ───────────────────────────────────────────────────────────
		const svg = createSvg(container, {
			width,
			height: svgH,
			ariaLabel: `${title} — small multiple matrix`
		});

		// ── Furniture ──────────────────────────────────────────────────────────
		addFurniture(svg, { width, height: svgH, title, subtitle, source });

		// ── Databox ────────────────────────────────────────────────────────────
		const box = createDataBox(svg, {
			width,
			fields: [
				{ key: 'lake', label: 'LAKE' },
				{ key: 'species', label: 'SPECIES' },
				{ key: 'year', label: 'YEAR' },
				{ key: 'catch', label: 'CATCH (t. lbs)' }
			],
			y: TITLE_H + 4,
			prompt: 'Hover a panel to explore'
		});
		box.btnG.on('click', () => box.clear());

		// ── Column headers ─────────────────────────────────────────────────────
		SPECIES.forEach((sp, ci) => {
			const cx = ML + ROW_LBL_W + ci * CW;
			const mid = cx + PAD.l + (CW - PAD.l - PAD.r) / 2;
			svg
				.append('text')
				.attr('x', mid)
				.attr('y', GRID_TOP + 11)
				.attr('text-anchor', 'middle')
				.style('font-family', type.sans)
				.style('font-size', '9px')
				.style('font-weight', 500)
				.style('fill', colors.ink)
				.text(SPECIES_LABELS[sp]);
			svg
				.append('text')
				.attr('x', mid)
				.attr('y', GRID_TOP + 23)
				.attr('text-anchor', 'middle')
				.style('font-family', type.sans)
				.style('font-size', '7.5px')
				.style('fill', colors.warmGray)
				.text(SPECIES_NOTES[sp]);
		});

		// ── Row separators ─────────────────────────────────────────────────────
		LAKES.forEach((_, ri) => {
			const gy = GRID_TOP + COL_HDR_H + ri * (CH + GAP_Y);
			svg
				.append('line')
				.attr('x1', ML)
				.attr('x2', width - MR)
				.attr('y1', gy)
				.attr('y2', gy)
				.attr('stroke', colors.gridLine)
				.attr('stroke-width', 0.5);
		});

		// ── Panels ─────────────────────────────────────────────────────────────
		LAKES.forEach((lake, ri) => {
			const gy = GRID_TOP + COL_HDR_H + ri * (CH + GAP_Y);

			svg
				.append('text')
				.attr('x', ML + ROW_LBL_W - 8)
				.attr('y', gy + CH / 2)
				.attr('text-anchor', 'end')
				.attr('dominant-baseline', 'middle')
				.style('font-family', type.sans)
				.style('font-size', '9px')
				.style('font-weight', 500)
				.style('fill', colors.ink)
				.text(lake);

			SPECIES.forEach((sp, ci) => {
				const gx = ML + ROW_LBL_W + ci * CW;
				const series = RAW[lake][sp];
				const localMax = d3.max(series, (d) => d.y) || 1;
				const ySc = d3
					.scaleLinear()
					.domain([0, localMax])
					.range([CH - PAD.b, PAD.t])
					.nice();

				const g = svg
					.append('g')
					.attr('transform', `translate(${gx}, ${gy})`)
					.style('cursor', 'crosshair');

				const clipId = `glclip-${ri}-${ci}`;
				svg
					.append('defs')
					.append('clipPath')
					.attr('id', clipId)
					.append('rect')
					.attr('x', PAD.l)
					.attr('y', PAD.t)
					.attr('width', CW - PAD.l - PAD.r)
					.attr('height', CH - PAD.t - PAD.b);

				// Ghost lines
				const ghostG = g
					.append('g')
					.attr('clip-path', `url(#${clipId})`)
					.attr('pointer-events', 'none');
				LAKES.forEach((otherLake, oi) => {
					if (oi === ri) return;
					ghostG
						.append('path')
						.attr('d', lineFn(yGlobal)(RAW[otherLake][sp]))
						.attr('fill', 'none')
						.attr('stroke', colors.warmGray)
						.attr('stroke-width', 0.75)
						.attr('opacity', 0.35);
				});

				// Grid ticks
				const yTicks = ySc.ticks(3);
				yTicks.forEach((t) => {
					g.append('line')
						.attr('x1', PAD.l)
						.attr('x2', CW - PAD.r)
						.attr('y1', ySc(t))
						.attr('y2', ySc(t))
						.attr('stroke', colors.warmGray)
						.attr('stroke-width', 0.5)
						.attr('opacity', 0.4)
						.attr('pointer-events', 'none');
				});

				// Left axis spine + baseline
				g.append('line')
					.attr('x1', PAD.l)
					.attr('x2', PAD.l)
					.attr('y1', PAD.t)
					.attr('y2', CH - PAD.b)
					.attr('stroke', colors.gridLine)
					.attr('stroke-width', 0.75);
				g.append('line')
					.attr('x1', PAD.l)
					.attr('x2', CW - PAD.r)
					.attr('y1', CH - PAD.b)
					.attr('y2', CH - PAD.b)
					.attr('stroke', colors.warmGray)
					.attr('stroke-width', 0.75);

				// Y labels
				const domMax = ySc.domain()[1];
				g.append('text')
					.attr('x', PAD.l - 3)
					.attr('y', PAD.t + 1)
					.attr('text-anchor', 'end')
					.attr('dominant-baseline', 'hanging')
					.style('font-size', '8px')
					.style('fill', colors.warmGray)
					.text(fmtY(domMax));
				g.append('text')
					.attr('x', PAD.l - 3)
					.attr('y', CH - PAD.b)
					.attr('text-anchor', 'end')
					.attr('dominant-baseline', 'auto')
					.style('font-size', '8px')
					.style('fill', colors.warmGray)
					.text('0');
				if (yTicks.length > 1) {
					const mid = yTicks[Math.floor(yTicks.length / 2)];
					g.append('text')
						.attr('x', PAD.l - 3)
						.attr('y', ySc(mid))
						.attr('text-anchor', 'end')
						.attr('dominant-baseline', 'middle')
						.style('font-size', '7.5px')
						.style('fill', colors.warmGray)
						.text(fmtY(mid));
					g.append('line')
						.attr('x1', PAD.l - 2)
						.attr('x2', PAD.l)
						.attr('y1', ySc(mid))
						.attr('y2', ySc(mid))
						.attr('stroke', colors.warmGray)
						.attr('stroke-width', 0.5);
				}

				// X labels — bottom row only
				if (ri === ROWS - 1) {
					g.append('text')
						.attr('x', PAD.l)
						.attr('y', CH - PAD.b + 12)
						.style('font-size', '8px')
						.style('fill', colors.warmGray)
						.text('1960');
					g.append('text')
						.attr('x', CW - PAD.r)
						.attr('y', CH - PAD.b + 12)
						.attr('text-anchor', 'end')
						.style('font-size', '8px')
						.style('fill', colors.warmGray)
						.text('2020');
				}

				// Main line
				g.append('path')
					.attr('d', lineFn(ySc)(series))
					.attr('fill', 'none')
					.attr('stroke', colors.sageDark)
					.attr('stroke-width', 1.75)
					.attr('clip-path', `url(#${clipId})`)
					.attr('pointer-events', 'none');

				// Cursor + dot
				const cursor = g
					.append('line')
					.attr('y1', PAD.t)
					.attr('y2', CH - PAD.b)
					.attr('stroke', colors.warmGray)
					.attr('stroke-width', 0.75)
					.attr('stroke-dasharray', '2,2')
					.style('opacity', 0)
					.attr('pointer-events', 'none');
				const dot = g
					.append('circle')
					.attr('r', 3)
					.attr('fill', colors.sageDark)
					.attr('stroke', colors.canvas)
					.attr('stroke-width', 1.5)
					.style('opacity', 0)
					.attr('pointer-events', 'none');

				// Hit rect
				g.append('rect')
					.attr('x', 0)
					.attr('y', 0)
					.attr('width', CW)
					.attr('height', CH)
					.attr('fill', 'transparent')
					.on('mousemove', function (event) {
						const [mx] = d3.pointer(event, svg.node());
						const xi = xSc.invert(mx - gx);
						const pi = series.reduce(
							(b, d, i) => (Math.abs(d.x - xi) < Math.abs(series[b].x - xi) ? i : b),
							0
						);
						const d = series[pi];
						dot.attr('cx', xSc(d.x)).attr('cy', ySc(d.y)).style('opacity', 1);
						cursor.attr('x1', xSc(d.x)).attr('x2', xSc(d.x)).style('opacity', 0.5);
						box.show(
							{ lake, species: SPECIES_LABELS[sp], year: d.x, catch: d.y.toLocaleString() },
							colors.sageDark
						);
					})
					.on('mouseleave', function () {
						dot.style('opacity', 0);
						cursor.style('opacity', 0);
						box.clear();
					});
			});
		});

		// ── Accessibility table ────────────────────────────────────────────────
		addA11yTable(svg.node(), {
			caption: `${title} — data table`,
			columns: [
				{ key: 'lake', label: 'Lake' },
				{ key: 'species', label: 'Species' },
				{ key: 'year', label: 'Year' },
				{ key: 'catch', label: 'Catch (t. lbs)' }
			],
			rows: LAKES.flatMap((lake) =>
				SPECIES.flatMap((sp) =>
					RAW[lake][sp].map((d) => ({
						lake,
						species: sp,
						year: d.x,
						catch: d.y.toFixed(1)
					}))
				)
			)
		});
	}
</script>

