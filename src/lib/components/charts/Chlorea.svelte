			.range([mapT + mapH, mapT]);

		const px = ([x, y]) => [xScale(x), yScale(y)];

		// ── <defs> ────────────────────────────────────────────────────────────────
		const defs = svg.append('defs');

		// Subtle drop shadow for death dots
		const shadow = defs
			.append('filter')
			.attr('id', 'dot-shadow')
			.attr('x', '-20%')
			.attr('y', '-20%')
			.attr('width', '140%')
			.attr('height', '140%');
		shadow
			.append('feDropShadow')
			.attr('dx', 0)
			.attr('dy', 0.5)
			.attr('stdDeviation', 0.8)
			.attr('flood-color', '#5A0F20')
			.attr('flood-opacity', 0.3);

		// Clip path for map area
		defs
			.append('clipPath')
			.attr('id', 'map-clip')
			.append('rect')
			.attr('x', mapL)
			.attr('y', mapT)
			.attr('width', mapW)
			.attr('height', mapH);

		// ── Map background — brand canvas colour ──────────────────────────────────
		svg
			.append('rect')
			.attr('x', mapL)
			.attr('y', mapT)
			.attr('width', mapW)
			.attr('height', mapH)
			.attr('fill', colors.canvas) // #F5F0E8 — brand canvas
			.attr('stroke', colors.gridLine)
			.attr('stroke-width', spacing.axisWidth)
			.attr('rx', 3);

		const mapG = svg.append('g').attr('clip-path', 'url(#map-clip)');

		// ── Streets — brand warm gray, fine stroke ────────────────────────────────
		streets.forEach((seg) => {
			if (seg.length < 2) return;
			const line = d3
				.line()
				.x((d) => xScale(d[0]))
				.y((d) => yScale(d[1]));
			mapG
				.append('path')
				.attr('d', line(seg))
				.attr('fill', 'none')
				.attr('stroke', '#C4BDB0') // slightly warmer than gridLine, reads as roads
				.attr('stroke-width', 1.2)
				.attr('stroke-linecap', 'round')
				.attr('stroke-linejoin', 'round');
		});

		// ── Death dots — brand roseDark, individual cases ─────────────────────────
		// Each point = one death. Slight jitter already present in the original data.
		mapG
			.selectAll('.death')
			.data(deaths)
			.join('circle')
			.attr('class', 'death')
			.attr('cx', (d) => xScale(d[0]))
			.attr('cy', (d) => yScale(d[1]))
			.attr('r', 3.5)
			.attr('fill', colors.roseDark) // #A8324A — brand accent
			.attr('fill-opacity', 0.75)
			.attr('stroke', '#7A1530')
			.attr('stroke-width', 0.3)
			.attr('filter', 'url(#dot-shadow)');

		// ── Pump markers — brand ink, rotated square (Snow's original symbol) ─────
		pumps.forEach(([x, y, label, id]) => {
			const [cx, cy] = px([x, y]);
			const isBroad = id === 7;
			const sz = isBroad ? 10 : 6;
			const fill = isBroad ? colors.ink : colors.sageDark;
			const stroke = isBroad ? colors.canvas : colors.sageLight;

			mapG
				.append('rect')
				.attr('x', cx - sz / 2)
				.attr('y', cy - sz / 2)
				.attr('width', sz)
				.attr('height', sz)
				.attr('fill', fill)
				.attr('stroke', stroke)
				.attr('stroke-width', isBroad ? 1.5 : 1)
				.attr('transform', `rotate(45,${cx},${cy})`);
		});

		// ── Legend — inline beneath subtitle, matches other charts in the system ────
		// addFurniture places title at y≈24, subtitle at y≈46, so legend sits at y≈62
		const lgG = svg.append('g').attr('transform', `translate(${PAD_L}, 62)`);

		// Death dot swatch
		lgG
			.append('circle')
			.attr('cx', 6)
			.attr('cy', 7)
			.attr('r', 3.5)
			.attr('fill', colors.roseDark)
			.attr('fill-opacity', 0.75)
			.attr('stroke', '#7A1530')
			.attr('stroke-width', 0.3);
		lgG
			.append('text')
			.attr('x', 16)
			.attr('y', 11)
			.style('font-family', type.sans)
			.style('font-size', '11px')
			.style('fill', colors.warmGray)
			.text('One death (578 total)');

		// Broad St pump swatch
		const bpx = 135,
			bpy = 7,
			bsz = 8;
		lgG
			.append('rect')
			.attr('x', bpx - bsz / 2)
			.attr('y', bpy - bsz / 2)
			.attr('width', bsz)
			.attr('height', bsz)
			.attr('fill', colors.ink)
			.attr('stroke', colors.canvas)
			.attr('stroke-width', 1)
			.attr('transform', `rotate(45,${bpx},${bpy})`);
		lgG
			.append('text')
			.attr('x', bpx + 10)
			.attr('y', 11)
			.style('font-family', type.sans)
			.style('font-size', '11px')
			.style('fill', colors.warmGray)
			.text('Broad Street pump');

		// Other pump swatch
		const opx = 278,
			opy = 7,
			osz = 6;
		lgG
			.append('rect')
			.attr('x', opx - osz / 2)
			.attr('y', opy - osz / 2)
			.attr('width', osz)
			.attr('height', osz)
			.attr('fill', colors.sageDark)
			.attr('stroke', colors.sageLight)
			.attr('stroke-width', 1)
			.attr('transform', `rotate(45,${opx},${opy})`);
		lgG
			.append('text')
			.attr('x', opx + 10)
			.attr('y', 11)
			.style('font-family', type.sans)
			.style('font-size', '11px')
			.style('fill', colors.warmGray)
			.text('Other water pump (12)');

		// ── Compass rose — top right corner ───────────────────────────────────────
		const cX = mapL + mapW - 26,
			cY = mapT + 30;
		mapG
			.append('text')
			.attr('x', cX)
			.attr('y', cY - 12)
			.attr('text-anchor', 'middle')
			.style('font-family', type.sans)
			.style('font-size', '10px')
			.style('fill', colors.warmGray)
			.text('N');
		mapG
			.append('line')
			.attr('x1', cX)
			.attr('y1', cY - 9)
			.attr('x2', cX)
			.attr('y2', cY + 9)
			.attr('stroke', colors.warmGray)
			.attr('stroke-width', 1);
		mapG
			.append('polygon')
			.attr('points', `${cX},${cY - 9} ${cX - 4},${cY} ${cX + 4},${cY}`)
			.attr('fill', colors.warmGray);

		// ── Accessibility table ───────────────────────────────────────────────────
		addA11yTable(svg.node(), {
			caption: `${title} — data table`,
			columns: [
				{ key: 'case', label: 'Case number' },
				{ key: 'x', label: 'X coordinate' },
				{ key: 'y', label: 'Y coordinate' }
			],
			rows: deaths.map((d, i) => ({ case: i + 1, x: d[0], y: d[1] }))
		});
	}
</script>

